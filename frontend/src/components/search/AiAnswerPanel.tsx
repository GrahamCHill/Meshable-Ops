import { Link } from 'react-router-dom'
import type { AiAnswer } from '../../api/ai'
import { storageLink } from './storageLink'

export function AiAnswerPanel({ answer, onNavigate }: { answer: AiAnswer; onNavigate?: () => void }) {
  return <section className="page-stack" aria-label="AI answer" aria-live="polite">
    <div><h2 className="card-title">{answer.grounded ? 'Answer from your documents' : 'No grounded answer available'}</h2><p style={{ whiteSpace: 'pre-wrap', overflowWrap: 'anywhere' }}>{answer.answer}</p></div>
    {!!answer.sources.length && <div className="page-stack"><h3 className="card-title">Sources</h3>{answer.sources.map(source => <article key={source.pointId}><Link to={storageLink(source.folderId, source.path)} onClick={onNavigate}>[{source.number}] {source.title}</Link><p className="field-help" style={{ marginTop: 6 }}>{source.path}</p><p style={{ whiteSpace: 'pre-wrap', overflowWrap: 'anywhere', fontSize: '0.85rem' }}>{source.excerpt}</p></article>)}</div>}
    {answer.model && <p className="field-help">Generated by {answer.model} using the excerpts above.</p>}
  </section>
}
